export type NameTheme = keyof typeof NAME_THEMES;
const THEMES = Object.keys(NAME_THEMES) as NameTheme[];

/**
 * Un nom au hasard (univers puis nom), jamais l'un de `taken` (noms du jardin, sans accents ni
 * casse) ni `previous` (le nom affiché, pour qu'« Autre nom » change toujours).
 */
export function suggestName(
  taken: readonly string[],
  previous: string | null = null,
  random: () => number = Math.random,
): string {
  const excluded = new Set([...taken, ...(previous ? [previous] : [])].map(normalize));
  const start = Math.floor(random() * THEMES.length);
  for (let k = 0; k < THEMES.length; k += 1) {
    const names = NAME_THEMES[THEMES[(start + k) % THEMES.length]!];
    const free = names.filter((n) => !excluded.has(normalize(n)));
    if (free.length) return free[Math.floor(random() * free.length)]!;
  }
  // Tous les noms pris (300 plantes dans un même jardin) : un numéro.
  let n = 2;
  while (excluded.has(normalize(`${NAME_THEMES.japonais[0]} ${n}`))) n += 1;
  return `${NAME_THEMES.japonais[0]} ${n}`;
}
